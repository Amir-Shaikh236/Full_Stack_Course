// React Router:
// React router is a library used in react to manage client-side routing by mapping URL paths to components without reloading the page.

// Advantages:
// 1. Client side Routing: Enables navigation wihtout full page reloads.
// 2. URL Mapping: Connects URL paths to specific components.
// 3. Dynamic Navigation: Allows seamless switching between views
// 4. Improved Performance: Updates only required components instead of the whole page.

// Types of React Routers:
// 1. BrowserRouter: URL from Browser address bar like (/home, /about)
// 2. HashRouter: URL as Hash like (#home, #about)
// 3. MemoryRouter: it is used in non-browser environment such as in react native or while running tests.

